#!/usr/bin/env python3
"""Build local web fonts without changing the original fonts or their coverage.

Optional regeneration (not needed for npm build):
  python3 -m venv /tmp/portfolio-fonts
  /tmp/portfolio-fonts/bin/pip install 'fonttools[woff]==4.67.0'
  /tmp/portfolio-fonts/bin/python scripts/subset-fonts.py

New characters continue to use the original variable font automatically.
"""

from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'src/assets/rem-world'


def unicode_ranges(codepoints):
    """Compress a cmap into CSS unicode-range descriptors."""
    ranges = []
    start = end = None
    for value in sorted(codepoints):
        if end is not None and value == end + 1:
            end = value
            continue
        if start is not None:
            ranges.append((start, end))
        start = end = value
    if start is not None:
        ranges.append((start, end))
    return ', '.join(
        f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}'
        for start, end in ranges
    )


def main():
    source_files = [ROOT / 'index.html']
    source_files += sorted(
        path for path in (ROOT / 'src').rglob('*')
        if path.suffix in {'.js', '.jsx', '.ts', '.tsx'}
    )
    characters = set(range(0x20, 0x100))
    for path in source_files:
        characters.update(map(ord, path.read_text(encoding='utf-8')))

    font = TTFont(ASSETS / 'pretendard.woff2', recalcTimestamp=False)
    full_coverage = set(font.getBestCmap())
    common_coverage = full_coverage & characters

    options = subset.Options()
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    options.glyph_names = True
    options.layout_features = ['*']
    options.recalc_timestamp = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=common_coverage)
    subsetter.subset(font)

    # The original's OFL reserves its font name. Rename the derived font while
    # retaining copyright, license, outlines, hinting, and the weight axis.
    names = {
        1: 'Rem Portfolio Sans',
        3: 'RemPortfolioSans;portfolio-subset',
        4: 'Rem Portfolio Sans',
        6: 'RemPortfolioSans-Regular',
        16: 'Rem Portfolio Sans',
        25: 'RemPortfolioSans',
    }
    for record in font['name'].names:
        if record.nameID in names:
            font['name'].setName(
                names[record.nameID], record.nameID,
                record.platformID, record.platEncID, record.langID,
            )
    font.flavor = 'woff2'
    font.save(ASSETS / 'portfolio-sans.woff2')

    display_font = TTFont(ASSETS / 'barlow-900.ttf', recalcTimestamp=False)
    display_font.flavor = 'woff2'
    display_font.save(ASSETS / 'barlow-900.woff2')

    # The last matching face wins for covered characters. The complete original
    # cmap stays available for future text; unsupported symbols use system fonts.
    css = f'''/* Generated by scripts/subset-fonts.py. Original OFL licenses apply. */
@font-face {{
  font-family: Barlow;
  src: url('./barlow-900.woff2') format('woff2');
  font-weight: 900;
  font-style: normal;
  font-display: swap;
}}
@font-face {{
  font-family: 'Portfolio Sans';
  src: url('./pretendard.woff2') format('woff2');
  font-weight: 100 900;
  font-style: normal;
  font-display: swap;
  unicode-range: {unicode_ranges(full_coverage)};
}}
@font-face {{
  font-family: 'Portfolio Sans';
  src: url('./portfolio-sans.woff2') format('woff2');
  font-weight: 100 900;
  font-style: normal;
  font-display: swap;
  unicode-range: {unicode_ranges(common_coverage)};
}}
'''
    (ASSETS / 'fonts.css').write_text(css, encoding='utf-8')
    for filename in ['portfolio-sans.woff2', 'barlow-900.woff2']:
        print(f'{filename}: {(ASSETS / filename).stat().st_size:,} bytes')
    print(f'Common coverage: {len(common_coverage):,} / {len(full_coverage):,} characters')


if __name__ == '__main__':
    main()
